"""Build assets/tdm-sample.js from the real HSL city bike origin-destination file.

Source rows: Helsinki Region Transport (HSL), "City bike stations' Origin-Destination (OD) data",
May 2021 monthly file https://dev.hsl.fi/citybikes/od-trips-2021/2021-05.csv
Licence: Creative Commons Attribution 4.0 (catalogue record on avoindata.fi, read 2026-11-16;
copy in materials/sources/od-pkg.json). The catalogue says the data is owned by City Bike Finland.
Station reference: HSL "city bicycle stations" CSV, CC BY 4.0 (materials/sources/stations.csv).

What ships: every unique trip departing from the five busiest departure stations of May 2021,
seeded 50% sample. The published file carries every row exactly twice (407,338 distinct rows,
814,676 lines); the sample ships each distinct row once and the bench loader re-creates the
doubling, which is a fact about the source, not an invention.

Constructed additions (labelled on the widget): a capacity-history table with older rows for two
stations (for the join fan-out bug) and a stale station snapshot (for the stale reference bug).

Usage: python3 build_tdm_sample.py <path to 2021-05.csv> <path to stations.csv> <out js>
"""
import csv
import json
import random
import sys
from datetime import datetime

SEED = 20210501
FORECAST = ["030", "126", "113", "041", "021"]
MONTH0 = datetime(2021, 5, 1, 0, 0, 0)
STALE_FROM = 300   # constructed: the stale snapshot lacks every station with id >= 300 that opened later
HISTORY = {"126": 20, "113": 16}  # constructed: older capacity rows still present in the history table


def main(trips_path, stations_path, out_path):
    with open(trips_path, encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))[1:]
    seen = set()
    uniq = []
    for r in rows:
        t = tuple(r)
        if t in seen:
            continue
        seen.add(t)
        uniq.append(r)
    keep = [r for r in uniq if r[2] in FORECAST]
    keep.sort(key=lambda r: (r[0], r[2], r[4], r[7], r[6]))
    rng = random.Random(SEED)
    sample = [r for r in keep if rng.random() < 0.5]

    ref = {}
    with open(stations_path, encoding="utf-8-sig") as f:
        for s in csv.DictReader(f):
            ref["%03d" % int(s["ID"])] = (int(s["Kapasiteet"]), s["Kaupunki"].strip() or "Helsinki", s["Name"])

    ids = list(FORECAST)
    for r in sample:
        if r[4] not in ids:
            ids.append(r[4])
    idx = {k: i for i, k in enumerate(ids)}
    ref_ids = sorted(k for k in ids if k in ref)

    dsec, dur, dist, s, rr = [], [], [], [], []
    prev = 0
    for r in sample:
        t = int((datetime.strptime(r[0], "%Y-%m-%dT%H:%M:%S") - MONTH0).total_seconds())
        dsec.append(t - prev)
        prev = t
        dur.append(int(float(r[7])))
        dist.append(int(float(r[6])))
        s.append(FORECAST.index(r[2]))
        rr.append(idx[r[4]])

    data = {
        "meta": {
            "source": "HSL city bike origin-destination trips, Helsinki and Espoo, May 2021",
            "url": "https://dev.hsl.fi/citybikes/od-trips-2021/2021-05.csv",
            "licence": "CC BY 4.0 (data owned by City Bike Finland, published by HSL)",
            "sample": "every distinct trip departing the five busiest stations, seeded 50% sample",
            "seed": SEED,
            "rawLines": len(rows),
            "rawDistinct": len(uniq),
            "forecast": FORECAST,
            "names": [ref[k][2] for k in FORECAST],
        },
        "ids": ids,
        "ref": [[k, ref[k][0], ref[k][1]] for k in ref_ids],
        "history": [[k, HISTORY[k]] for k in sorted(HISTORY)],
        "staleFrom": STALE_FROM,
        "dsec": dsec,
        "dur": dur,
        "dist": dist,
        "s": s,
        "r": rr,
    }
    js = "/* generated by materials/build_tdm_sample.py - do not edit by hand */\nwindow.TDM_SAMPLE = " + \
        json.dumps(data, separators=(",", ":"), ensure_ascii=True) + ";\n"
    with open(out_path, "w") as f:
        f.write(js)
    print("trips", len(sample), "ids", len(ids), "ref", len(ref_ids), "bytes", len(js))


if __name__ == "__main__":
    main(*sys.argv[1:4])
